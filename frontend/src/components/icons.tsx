import type { ReactNode, SVGProps } from "react";

// Iconos en línea (M-02): sin texto propio; el nombre accesible lo pone el control que los contiene.
type IconProps = Omit<SVGProps<SVGSVGElement>, "children">;

function Icon({ name, children, ...props }: IconProps & { name: string; children: ReactNode }) {
  return (
    <svg
      data-icon={name}
      viewBox="0 0 24 24"
      width="18"
      height="18"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...props}
    >
      {children}
    </svg>
  );
}

export function SunIcon(props: IconProps) {
  return (
    <Icon name="sun" {...props}>
      <circle cx="12" cy="12" r="4" />
      <path d="M12 2v2M12 20v2M4.9 4.9l1.4 1.4M17.7 17.7l1.4 1.4M2 12h2M20 12h2M4.9 19.1l1.4-1.4M17.7 6.3l1.4-1.4" />
    </Icon>
  );
}

